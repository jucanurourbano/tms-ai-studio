def _tabla(nombre, columnas, **extra):
    base = {
        "id": f"TBL-{nombre}",
        "name": nombre,
        "columns": [
            {"id": f"COL-{nombre}-{c['name']}", "nullable": True, **c} for c in columnas
        ],
        "primary_key": {"name": f"pk_{nombre}", "columns": [columnas[0]["name"]]},
        "foreign_keys": [],
        "unique_constraints": [],
        "check_constraints": [],
        "indexes": [],
    }
    base.update(extra)
    base["columns"][0]["nullable"] = False
    return base


def test_l1_detecta_fk_a_tabla_inexistente():
    tabla = _tabla("siniestros", [{"name": "id", "logical_type": "bigint"}])
    tabla["foreign_keys"] = [
        {
            "id": "FK-001",
            "name": "fk_x",
            "columns": ["id"],
            "references_table": "no_existe",
            "references_columns": ["id"],
        }
    ]
    resultado = check_structure([tabla], [], ENGINE)
    assert any(e["code"] == "fk_target_missing" for e in resultado["errors"])
    assert resultado["checks"]["all_fks_resolve"] is False


