def test_l1_distingue_omitir_una_columna_con_default_de_pasarle_NULL():
    """Un NULL explícito NO activa el DEFAULT: la inserción falla igualmente.

    Regresión: el catálogo listaba TODAS sus columnas en el INSERT, así que
    `activo` (NOT NULL DEFAULT true) recibía NULL y la creación del esquema
    fallaba. Lo detectó la ejecución real (L3a), no la validación estática.
    """
    tabla = _tabla(
        "estados",
        [
            {"name": "estado_id", "logical_type": "bigint", "is_generated": True},
            {"name": "codigo", "logical_type": "string", "nullable": False},
            {
                "name": "activo",
                "logical_type": "boolean",
                "nullable": False,
                "default": "true",
            },
        ],
    )
    # Omitir `activo` es correcto: el motor aplica su DEFAULT.
    omitida = check_structure(
        [tabla],
        [
            {
                "id": "S1",
                "table": "estados",
                "columns": ["codigo"],
                "rows": [{"codigo": "A"}],
            }
        ],
        ENGINE,
    )
    assert omitida["errors"] == []

    # Listarla con NULL, no: el DEFAULT no se aplica.
    con_nulo = check_structure(
        [tabla],
        [
            {
                "id": "S2",
                "table": "estados",
                "columns": ["codigo", "activo"],
                "rows": [{"codigo": "A", "activo": None}],
            }
        ],
        ENGINE,
    )
    assert any(e["code"] == "seed_missing_required" for e in con_nulo["errors"])


