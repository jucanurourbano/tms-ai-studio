async def test_create_table_lleva_columnas_pk_unique_y_check():
    tables, _, _ = await _modelo_completo()
    siniestros = next(t for t in tables if t["name"] == "siniestros")
    sql = render_create_table(siniestros, ENGINE)

    assert sql.startswith("CREATE TABLE public.siniestros (")
    assert "siniestro_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL" in sql
    assert "CONSTRAINT pk_siniestros PRIMARY KEY (siniestro_id)" in sql
    # Las FK NO van aquí: viven en su propio script.
    assert "FOREIGN KEY" not in sql


async def test_las_fk_van_en_un_script_aparte():
    """Así el orden de creación deja de importar y un ciclo no rompe el esquema."""
    tables, seeds, _ = await _modelo_completo()
    scripts, _ = build_ddl_scripts(tables, seeds, ENGINE)
    por_tipo = {s["kind"]: s for s in scripts}

    assert "constraints" in por_tipo
    assert all(
        s.startswith("ALTER TABLE") and "FOREIGN KEY" in s
        for s in por_tipo["constraints"]["statements"]
    )
    assert por_tipo["constraints"]["order"] > por_tipo["tables"]["order"]


async def test_los_scripts_salen_ordenados_y_completos():
    tables, seeds, _ = await _modelo_completo()
    scripts, _ = build_ddl_scripts(tables, seeds, ENGINE)

    tipos = [s["kind"] for s in scripts]
    assert tipos[0] == "schema"  # PostgreSQL sí usa esquema
    assert "tables" in tipos and "indexes" in tipos and "seed" in tipos
    assert tipos[-1] == "rollback"
    assert [s["order"] for s in scripts] == sorted(s["order"] for s in scripts)

    for script in scripts:
        DdlScript.model_validate(script)
        assert script["engine"] == ENGINE
        # El texto completo termina cada sentencia con `;`.
        assert script["sql"].count(";") >= len(script["statements"])


async def test_el_rollback_es_destructivo_y_lo_avisa():
    tables, seeds, _ = await _modelo_completo()
    scripts, _ = build_ddl_scripts(tables, seeds, ENGINE)
    rollback = next(s for s in scripts if s["kind"] == "rollback")

    assert "DESTRUCTIVO" in rollback["sql"]
    assert all(s.startswith("DROP TABLE IF EXISTS") for s in rollback["statements"])
    # En orden inverso al de creación: los hijos primero.
    tablas_script = next(s for s in scripts if s["kind"] == "tables")
    creadas = [
        s.split("CREATE TABLE ")[1].split(" (")[0] for s in tablas_script["statements"]
    ]
    borradas = [s.split("IF EXISTS ")[1] for s in rollback["statements"]]
    assert borradas == list(reversed(creadas))


