ENGINE = "postgresql"


def _sources():
    return extract_sources(
        ef_example().model_dump(mode="json"),
        arquitectura_example().model_dump(mode="json"),
        None,
    )


async def _modelo_completo(engine: str = ENGINE):
    """Modelo tras BD3 + BD4: la entrada real de DDL_GEN."""
    sources = _sources()
    mapa = build_model_map(sources, engine)
    tables, _, _, _ = await run_tables(BdMapLLM(), mapa, sources, engine)
    tables, _, _, _ = await run_relations(BdMapLLM(), tables, mapa, sources, engine)
    tables, _, _, _, _ = await run_constraints(BdMapLLM(), tables, sources, engine)
    tables, _, _, _ = await run_indexes(BdMapLLM(), tables, sources, engine)
    tables, seeds, _, _, _ = await run_catalogs(BdMapLLM(), tables, sources, engine)
    for table in tables:
        for column in table["columns"]:
            column["type"] = render_type(column, engine)
    return tables, seeds, sources


# --- Traducción de tipos (DB2) ----------------------------------------------


@pytest.mark.parametrize(
    "logical,extra,esperado",
    [
        ("string", {"length": 30}, "VARCHAR(30)"),
        ("text", {}, "TEXT"),
        ("bigint", {}, "BIGINT"),
        ("decimal", {"precision": 10, "scale": 3}, "NUMERIC(10,3)"),
        ("boolean", {}, "BOOLEAN"),
        ("date", {}, "DATE"),
        ("timestamp", {}, "TIMESTAMP"),
        ("uuid", {}, "UUID"),
        ("json", {}, "JSONB"),
    ],
)
def test_tipos_logicos_se_traducen_a_postgresql(logical, extra, esperado):
    """PostgreSQL 16 es el motor validado de la casa: su traducción es la crítica."""
    assert render_type({"logical_type": logical, **extra}, "postgresql") == esperado


def test_el_mismo_modelo_cambia_de_dialecto_sin_volver_a_llamar_al_LLM():
    """La portabilidad de DB2: el tipo lógico es neutro y el render, por motor."""
    columna = {"logical_type": "string", "length": 50}
    assert render_type(columna, "postgresql") == "VARCHAR(50)"
    assert render_type(columna, "sqlserver") == "NVARCHAR(50)"
    assert render_type(columna, "oracle") == "VARCHAR2(50)"
    assert render_type(columna, "mysql") == "VARCHAR(50)"


def test_boolean_default_se_adapta_al_motor():
    """`TRUE` solo existe en PostgreSQL; en los demás el booleano es numérico."""
    columna = {"logical_type": "boolean", "default": "true"}
    assert render_default(columna, "postgresql") == "TRUE"
    assert render_default(columna, "sqlserver") == "1"
    assert render_default(columna, "mysql") == "1"
    assert render_default({"logical_type": "integer", "default": None}, ENGINE) is None


